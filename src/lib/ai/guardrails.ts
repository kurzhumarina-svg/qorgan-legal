/**
 * Программная проверка ответа модели перед отправкой клиенту.
 *
 * Промпт — это просьба, а не гарантия: модель может нарушить инструкцию.
 * Поэтому запреты из ТЗ продублированы кодом. Именно эти три вещи обещали
 * проверять на сдаче: выдуманные статьи закона, обещание исхода и лишние
 * персональные данные.
 */

export type Violation = 'law_reference' | 'outcome_promise' | 'sensitive_data';

type Rule = { id: Violation; label: string; pattern: RegExp };

const RULES: Rule[] = [
  {
    id: 'law_reference',
    label: 'ссылка на конкретную норму закона',
    // «ст. 123», «статья 456», «п. 2», «ч. 3», а также названия кодексов РК.
    pattern:
      /(?:\b(?:ст|стт|п|пп|ч)\.\s*\d+)|(?:\bстать[яьиеюё]\s*(?:№\s*)?\d+)|(?:\b(?:ГК|УК|ГПК|УПК|КоАП|АППК|НК|ТК)\s*РК\b)/i,
  },
  {
    id: 'outcome_promise',
    label: 'обещание исхода дела',
    pattern:
      /(?:гарантиру)|(?:гаранти[ияю]\s+(?:побед|результат|исход|возврат))|(?:\b100\s*%)|(?:стопроцентн)|(?:(?:точно|обязательно|наверняка|однозначно)\s+(?:выиграе|выигра|вернём|вернем|взыщ))|(?:дело\s+беспроигрышн)|(?:вернём\s+деньги\s+гарантир)/i,
  },
  {
    id: 'sensitive_data',
    label: 'запрос лишних персональных данных',
    // Ловим именно ПРОСЬБУ прислать данные, а не упоминание («ИИН присылать не нужно»).
    pattern:
      /(?:укажите|пришлите|отправьте|напишите|назовите|введите|скиньте|предоставьте)[^.?!\n]{0,60}(?:ИИН|номер\s+паспорта|паспортны|удостоверени[яе]\s+личности|номер\s+карты|реквизиты\s+карты|CVV|пин-?код)/i,
  },
];

export type GuardrailResult = {
  ok: boolean;
  violations: Violation[];
  /** Человекочитаемо — попадает в лог, помогает объяснить работу на защите. */
  labels: string[];
};

export function checkAnswer(text: string): GuardrailResult {
  const hits = RULES.filter((rule) => rule.pattern.test(text));
  return {
    ok: hits.length === 0,
    violations: hits.map((r) => r.id),
    labels: hits.map((r) => r.label),
  };
}
